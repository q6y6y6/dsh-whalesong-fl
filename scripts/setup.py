#!/usr/bin/env python3
"""Prepare DSH WhaleSong for FL Studio on this machine.

    .venv/bin/python scripts/setup.py                 # rewrite bundle paths, report
    .venv/bin/python scripts/setup.py --install-profile
    .venv/bin/python scripts/setup.py --dry-run

The profile edit is opt-in. It backs up the current profile patch before
appending the MCP entry and never touches other rows.
"""

from __future__ import annotations

import argparse
import os
import shutil
import subprocess
import sys
from datetime import datetime
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
BUNDLE = ROOT / "packages" / "dsh-bundle"
PATCH = BUNDLE / "cordis.patch.yml"
PROFILE = Path.home() / ".dsh" / "profiles" / "desktop" / "cordis.patch.yml"
VENV_PYTHON = ROOT / ".venv" / "bin" / "python"


def render_patch() -> str:
    return f"""# dsh-whalesong-fl bundle: connect the local FL Studio MCP server.
#
# Generated by scripts/setup.py. Keep `command` on the project virtualenv so
# mido/python-rtmidi stay pinned.
- insert:
    - id: fl-studio-mcp
      name: '@deepseek-ai/dsh-mcp-client'
      config:
        serverName: fl
        transport: stdio
        command: {VENV_PYTHON}
        args: ['-m', 'fl_melody.server']
        cwd: {ROOT}
        toolCallTimeoutMs: 30000
        failOnStartupError: false
"""


def ensure_venv() -> None:
    env = {**os.environ, "UV_CACHE_DIR": str(ROOT / ".uvcache")}
    if not VENV_PYTHON.is_file():
        print(f"Creating {ROOT / '.venv'} ...")
        subprocess.run(
            ["uv", "venv", str(ROOT / ".venv"), "--python", "3.12"],
            check=True,
            env=env,
        )
    for package in ("fl-v0", "fl-melody"):
        subprocess.run(
            [
                "uv",
                "pip",
                "install",
                "--python",
                str(VENV_PYTHON),
                "-e",
                str(ROOT / "packages" / package),
            ],
            check=True,
            env=env,
        )


def write_bundle_patch(dry_run: bool) -> None:
    text = render_patch()
    if dry_run:
        print(text)
        return
    PATCH.write_text(text, encoding="utf-8")
    print(f"Wrote {PATCH}")


def profile_has_entry() -> bool:
    if not PROFILE.is_file():
        return False
    return "fl-studio-mcp" in PROFILE.read_text(encoding="utf-8")


def install_profile(dry_run: bool) -> None:
    if profile_has_entry():
        print(f"Profile already has fl-studio-mcp: {PROFILE}")
        return
    if not PROFILE.is_file():
        print(f"Profile patch not found: {PROFILE}")
        print("Install the bundle through the DSH Plugins page instead.")
        return
    if dry_run:
        print("Would append the MCP entry to", PROFILE)
        return
    backup = ROOT / "backups" / f"desktop-cordis.patch.yml.{datetime.now():%Y%m%d-%H%M%S}"
    backup.parent.mkdir(parents=True, exist_ok=True)
    shutil.copy2(PROFILE, backup)
    text = PROFILE.read_text(encoding="utf-8").rstrip() + "\n" + render_patch()
    PROFILE.write_text(text, encoding="utf-8")
    print(f"Backed up to {backup}")
    print(f"Appended MCP entry to {PROFILE}")


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--install-profile", action="store_true")
    parser.add_argument("--dry-run", action="store_true")
    args = parser.parse_args()

    print(f"DSH WhaleSong root: {ROOT}")
    ensure_venv()
    write_bundle_patch(args.dry_run)
    if args.install_profile:
        install_profile(args.dry_run)
    print()
    print("Next steps:")
    print("  1. Open FL Studio on a disposable project.")
    print("  2. Run: .venv/bin/python scripts/doctor.py --live")
    print('  3. Run: .venv/bin/python scripts/melody_smoke.py --channel "Piano"')
    print("  4. In DSH, install packages/dsh-bundle or apply its patch, then")
    print("     restart/reload if the mcp__fl__* tools are not visible.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
